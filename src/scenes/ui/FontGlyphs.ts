// Szerokość glifu = długość wiersza (czcionka proporcjonalna); cyfry mają stałe 5 px (wyrównywanie liczb).
//
// Zapis: [pierwszy wiersz, 'wiersz wiersz ...'], '#' = piksel, '.' = pusto.

