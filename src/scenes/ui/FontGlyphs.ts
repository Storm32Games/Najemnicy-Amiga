/** Odstęp (spacja) - szerokość pustego glifu. */
export const SPACE_W = 3;

export interface Glyph {
  /** Szerokość w pikselach (bez odstępu). */
  w: number;
  /** Piksele glifu w układzie komórki (y = -1..7; -1 tylko dla znaków nad wielkimi literami). */
  px: readonly (readonly [number, number])[];
  /** Przesunięcie do następnego znaku. */
  adv: number;
}

/** Znaki ramek łączą się bez przerwy. */
const NO_GAP = new Set(['─', '═']);

function build(ch: string, spec: Spec, bold: boolean): Glyph {
  const [top, src] = spec;
  const rows = src.split(' ');
  const w0 = rows.reduce((m, r) => Math.max(m, r.length), 0);
  const set = new Set<string>();
  // glify z 1-pikselowymi przerwami (W M m w # ...) po pogrubieniu straciłyby kształt - zostają cienkie
  const thicken = bold && !rows.some((r) => /#\.#/.test(r));
  rows.forEach((row, dy) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') {
      set.add(`${x},${top + dy}`);
      // pogrubienie: piksel podwojony w prawo (rozmiar piksela się nie zmienia)
      if (thicken) set.add(`${x + 1},${top + dy}`);
    }
  });
  const w = w0 + (bold ? 1 : 0);
  const px = [...set].map((k) => k.split(',').map(Number) as [number, number]);
  return { w, px, adv: w + (NO_GAP.has(ch) ? 0 : SPACING) };
}

const cache: Record<'r' | 'b', Map<string, Glyph>> = { r: new Map(), b: new Map() };

/** Zestaw wszystkich narysowanych znaków. */
export const CHARSET: readonly string[] = [' ', ...Object.keys(RAW)];

/** Glif znaku (z zastępstwem: litera bez akcentu, potem '?'). */
export function glyph(ch: string, bold = false): Glyph {
  const c = cache[bold ? 'b' : 'r'];
  let g = c.get(ch);
  if (g) return g;
  if (ch === ' ') g = { w: SPACE_W - SPACING, px: [], adv: SPACE_W + (bold ? 1 : 0) };
  else {
    const spec = RAW[ch] ?? RAW[ch.normalize('NFD').replace(/[̀-ͯ]/g, '')] ?? RAW['?'];
    g = build(ch, spec, bold);
  }
  c.set(ch, g);
  return g;
}

export function hasGlyph(ch: string): boolean {
  return ch === ' ' || ch in RAW;
}

/** Piksele napisu w jednej linii (do malowania na PixelCanvas / canvasie). */
export function textPixels(str: string, bold = false): { px: [number, number][]; w: number; h: number } {
  const out: [number, number][] = [];
  let x = 0;
  for (const ch of str) {
    const g = glyph(ch, bold);
    for (const [gx, gy] of g.px) out.push([x + gx, gy]);
    x += g.adv;
  }
  return { px: out, w: Math.max(0, x - SPACING), h: CELL_H };
}

/** Szerokość napisu w pikselach. */
export function measure(str: string, bold = false): number {
  let x = 0;
  for (const ch of str) x += glyph(ch, bold).adv;
  return Math.max(0, x - SPACING);
}

/** Przycina napis z wielokropkiem, tak by mieścił się w maxW pikselach. */
export function fitText(str: string, maxW: number, bold = false): string {
  if (measure(str, bold) <= maxW) return str;
  const chars = [...str];
  while (chars.length && measure(chars.join('').trimEnd() + '…', bold) > maxW) chars.pop();
  return chars.join('').trimEnd() + '…';
}
